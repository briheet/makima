// swift-tools-version: 6.2
import Foundation
import PackageDescription

/// Where `just core` puts `libmakima_ffi.a`.
let rustLibDirectory = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()
    .appendingPathComponent("../../target/release")
    .standardizedFileURL
    .path

/// Embedded in the executable (there's no app bundle when run from SwiftPM):
/// a bundle id, and the usage descriptions macOS requires for the microphone.
let infoPlist = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()
    .appendingPathComponent("Support/Info.plist")
    .path

/// `MAKIMA_STRICT=1` (set by `just lint` and CI) turns warnings into errors
/// in Makima's own targets, leaving dependencies alone.
let strictSettings: [SwiftSetting] =
    ProcessInfo.processInfo.environment["MAKIMA_STRICT"] == "1" ? [.unsafeFlags(["-warnings-as-errors"])] : []

/// Concurrency settings every target uses (see docs/swift-practices.md).
let concurrencySettings: [SwiftSetting] = [
    .enableUpcomingFeature("NonisolatedNonsendingByDefault"),
    .enableUpcomingFeature("InferIsolatedConformances"),
]

/// Settings shared by every hand-written target.
let commonSettings: [SwiftSetting] =
    concurrencySettings + strictSettings + [
        .enableUpcomingFeature("MemberImportVisibility"),
        .enableUpcomingFeature("ExistentialAny"),
    ]

/// UI targets run on the main actor unless they opt out.
let uiSettings: [SwiftSetting] = commonSettings + [.defaultIsolation(MainActor.self)]

let package = Package(
    name: "Makima",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "MakimaApp", targets: ["MakimaApp"])
    ],
    dependencies: [
        .package(url: "https://github.com/Lakr233/libghostty-spm.git", from: "2.2.2026100501")
    ],
    targets: [
        // C header and modulemap generated by uniffi-bindgen-swift.
        .systemLibrary(
            name: "MakimaCoreFFI",
            path: "Sources/MakimaCoreFFI"
        ),
        // The Swift bindings uniffi-bindgen-swift generates, plus the typed
        // IDs they use (Generated/ is rebuilt by `just bindings`).
        //
        // Deliberate exception to commonSettings: generated code doesn't
        // compile with ExistentialAny or MemberImportVisibility. Nonisolated
        // (no default MainActor): Rust calls into it from any thread.
        .target(
            name: "MakimaCoreBindings",
            dependencies: ["MakimaCoreFFI"],
            swiftSettings: concurrencySettings + strictSettings,
            linkerSettings: [
                .unsafeFlags(["-L", rustLibDirectory]),
                .linkedLibrary("makima_ffi"),
            ]
        ),
        // The Rust core for the app: domain types, CoreClient, config and
        // the chrome facade, over the bindings. Nonisolated and Sendable.
        .target(
            name: "MakimaCore",
            dependencies: ["MakimaCoreBindings"],
            swiftSettings: commonSettings
        ),
        // libghostty integration.
        .target(
            name: "MakimaTerminal",
            dependencies: [
                .product(name: "GhosttyTerminal", package: "libghostty-spm"),
                .product(name: "GhosttyTheme", package: "libghostty-spm"),
            ],
            swiftSettings: uiSettings
        ),
        // Recording and on-device transcription (no default main actor:
        // transcription runs off the main thread).
        .target(
            name: "MakimaVoice",
            swiftSettings: commonSettings,
            linkerSettings: [
                .linkedFramework("Speech"), .linkedFramework("AVFoundation"), .linkedFramework("Security"),
            ]
        ),
        // View models, sidebar and window content.
        .target(
            name: "MakimaUI",
            dependencies: [
                "MakimaCore",
                // Only for the chrome's presentation types and engines
                // (see TerminalChrome.swift); everything else goes through
                // MakimaCore.
                "MakimaCoreBindings",
                "MakimaTerminal",
                "MakimaVoice",
                .product(name: "GhosttyTerminal", package: "libghostty-spm"),
            ],
            swiftSettings: uiSettings
        ),
        .executableTarget(
            name: "MakimaApp",
            dependencies: ["MakimaUI", "MakimaCore", "MakimaCoreBindings"],
            swiftSettings: uiSettings,
            linkerSettings: [
                .unsafeFlags([
                    "-Xlinker", "-sectcreate", "-Xlinker", "__TEXT", "-Xlinker", "__info_plist", "-Xlinker", infoPlist,
                ])
            ]
        ),
        .testTarget(
            name: "MakimaUITests",
            dependencies: ["MakimaUI", "MakimaCore", "MakimaCoreBindings", "MakimaVoice", "MakimaTerminal"],
            swiftSettings: uiSettings
        ),
    ],
    swiftLanguageModes: [.v6]
)
